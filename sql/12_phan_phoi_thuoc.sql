--
-- Tab "Phân phối thuốc": bảng phân phối theo văn bản (VB) của kho tuyến trên.
--   pp_docs      : mỗi dòng = 1 văn bản phân phối (số VB, ngày, quý, kho lập bảng)
--   pp_lines     : số lượng phân cho từng đơn vị × thuốc trong văn bản (KHÔNG có lô / hạn)
--   pp_receipts  : đơn vị nhận ghi nhận theo văn bản
--                    kind = 'done' : đánh dấu "đã nhận đủ" văn bản (ngày nhận, ghi chú)
--                    kind = 'link' : số "Nhập tuyến trên" của 1 lô trong báo cáo thuộc văn bản nào
-- Quyền GHI (kiểm tra ở trigger, giống các bảng khác):
--   • pp_docs / pp_lines : admin, hoặc tài khoản của CHÍNH kho lập bảng (from_unit_id).
--   • pp_receipts        : admin, hoặc tài khoản của chính đơn vị nhận (unit_id).
-- Quyền ĐỌC: như các bảng báo cáo khác (ứng dụng lọc theo phạm vi tài khoản).
-- ═══════════════════════════════════════════════════════════════════════

create table if not exists public.pp_docs(
  id            uuid primary key default gen_random_uuid(),
  from_unit_id  uuid not null,
  period        text not null,                 -- 'YYYY-Qn'
  so_vb         text not null default '',
  ngay_vb       date,
  title         text not null default '',      -- vd "Dành cho các tỉnh khu vực miền Bắc"
  note          text not null default '',
  created_by    text,
  created_at    timestamptz not null default now(),
  constraint pp_docs_period_chk check (period ~ '^\d{4}-Q[1-4]$')
);
create index if not exists ix_pp_docs_period on public.pp_docs(period, from_unit_id);

create table if not exists public.pp_lines(
  id          bigint generated by default as identity primary key,
  doc_id      uuid not null references public.pp_docs(id) on delete cascade,
  to_unit_id  uuid not null,
  drug        text not null,
  qty         numeric not null default 0,
  constraint pp_lines_qty_chk check (qty >= 0),
  constraint ux_pp_lines unique (doc_id, to_unit_id, drug)
);
create index if not exists ix_pp_lines_unit on public.pp_lines(to_unit_id);

create table if not exists public.pp_receipts(
  id             bigint generated by default as identity primary key,
  doc_id         uuid not null references public.pp_docs(id) on delete cascade,
  unit_id        uuid not null,
  kind           text not null default 'done',
  period         text not null default '',     -- kỳ báo cáo của dòng nhập (chỉ với kind = 'link')
  drug           text not null default '',
  lot            text not null default '',
  exp            text not null default '',
  qty            numeric not null default 0,
  received_date  date,
  note           text not null default '',
  created_by     text,
  created_at     timestamptz not null default now(),
  constraint pp_receipts_kind_chk check (kind in ('done', 'link')),
  constraint pp_receipts_qty_chk check (qty >= 0),
  constraint ux_pp_receipts unique (doc_id, unit_id, kind, period, drug, lot, exp)
);
create index if not exists ix_pp_receipts_unit on public.pp_receipts(unit_id);

grant select, insert, update, delete on public.pp_docs, public.pp_lines, public.pp_receipts to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

-- ── Trigger kiểm tra ghi ─────────────────────────────────────────────────
-- KHÔNG security definer: current_user = vai trò thật của request (REST từ trình duyệt = anon/authenticated).
create or replace function public.trg_pp_guard()
returns trigger language plpgsql set search_path = public
as $$
declare s public.app_sessions; v_owner text; v_doc uuid; v_admin boolean;
begin
  if current_user not in ('anon', 'authenticated') then
    return case when TG_OP = 'DELETE' then OLD else NEW end;
  end if;
  s := app_private._app_sess();
  if s.token is null then raise exception 'ERR_SESSION: cần đăng nhập để ghi dữ liệu (%)', TG_TABLE_NAME; end if;
  v_admin := coalesce(s.role, '') = 'admin';

  if TG_TABLE_NAME = 'pp_docs' then
    if TG_OP in ('INSERT', 'UPDATE') then
      NEW.created_by := coalesce(case when TG_OP = 'UPDATE' then OLD.created_by end, s.user_id);
      if TG_OP = 'UPDATE' and NEW.from_unit_id is distinct from OLD.from_unit_id and not v_admin then
        raise exception 'ERR_FORBIDDEN: không đổi được kho lập bảng';
      end if;
    end if;
    v_owner := case when TG_OP = 'DELETE' then OLD.from_unit_id::text else NEW.from_unit_id::text end;
    if not v_admin and v_owner is distinct from s.unit_id then
      raise exception 'ERR_FORBIDDEN: chỉ kho lập bảng (hoặc quản trị viên) được sửa bảng phân phối';
    end if;

  elsif TG_TABLE_NAME = 'pp_lines' then
    v_doc := case when TG_OP = 'DELETE' then OLD.doc_id else NEW.doc_id end;
    select d.from_unit_id::text into v_owner from public.pp_docs d where d.id = v_doc;
    -- Văn bản vừa bị xoá (xoá dây chuyền): quyền đã được kiểm tra ở dòng pp_docs → cho qua
    if not found and TG_OP = 'DELETE' then return OLD; end if;
    if not v_admin and v_owner is distinct from s.unit_id then
      raise exception 'ERR_FORBIDDEN: chỉ kho lập bảng (hoặc quản trị viên) được sửa bảng phân phối';
    end if;

  elsif TG_TABLE_NAME = 'pp_receipts' then
    if TG_OP in ('INSERT', 'UPDATE') then
      NEW.created_by := coalesce(case when TG_OP = 'UPDATE' then OLD.created_by end, s.user_id);
    end if;
    if TG_OP = 'DELETE' and not exists (select 1 from public.pp_docs d where d.id = OLD.doc_id) then
      return OLD;   -- xoá dây chuyền theo văn bản (kho lập bảng xoá văn bản của mình)
    end if;
    v_owner := case when TG_OP = 'DELETE' then OLD.unit_id::text else NEW.unit_id::text end;
    if not v_admin and v_owner is distinct from s.unit_id then
      raise exception 'ERR_FORBIDDEN: chỉ đơn vị nhận (hoặc quản trị viên) được ghi nhận theo văn bản';
    end if;
  end if;

  return case when TG_OP = 'DELETE' then OLD else NEW end;
end $$;

do $$
declare t text;
begin
  foreach t in array array['pp_docs', 'pp_lines', 'pp_receipts'] loop
    execute format('drop trigger if exists trg_pp_guard on public.%I', t);
    execute format('create trigger trg_pp_guard before insert or update or delete on public.%I
                    for each row execute function public.trg_pp_guard()', t);
  end loop;
end $$;

-- ── RLS: theo đúng cách các bảng báo cáo đang dùng ──────────────────────
-- Nếu bảng reports đang bật RLS thì bật RLS cho 3 bảng mới với chính sách "đọc/ghi qua anon key"
-- (quyền ghi thật do trigger ở trên quyết định). Nếu reports không bật RLS thì để nguyên.
do $$
declare t text; v_rls boolean;
begin
  select c.relrowsecurity into v_rls from pg_class c where c.oid = 'public.reports'::regclass;
  if coalesce(v_rls, false) then
    foreach t in array array['pp_docs', 'pp_lines', 'pp_receipts'] loop
      execute format('alter table public.%I enable row level security', t);
      execute format('drop policy if exists pp_all on public.%I', t);
      execute format('create policy pp_all on public.%I for all to anon, authenticated using (true) with check (true)', t);
    end loop;
  end if;
end $$;

notify pgrst, 'reload schema';

